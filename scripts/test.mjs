import assert from 'node:assert/strict';
import {test} from 'node:test';
import worker from '../dist/server/index.js';
import {createDatabase,mockServices} from './local-db.mjs';

test('guest testing works without mail and isolates keys, history, expiry and deletion',async()=>{
  const DB=createDatabase(),mocks=mockServices();
  const env={DB,PRISM_SECRET:'local-test-secret-only'};
  const origin='https://prism.test';
  async function request(path,data,method='POST',cookie='',originHeader=origin) {
    const response=await worker.fetch(new Request(origin+'/api'+path,{method,headers:{Origin:originHeader,Cookie:cookie,'Content-Type':'application/json'},body:method==='GET'?undefined:JSON.stringify(data||{})}),env,{});
    return {response,status:response.status,data:await response.json()};
  }
  try {
    assert.equal((await request('/auth/guest')).status,403);
    env.ALLOW_GUEST_TEST='true';
    assert.equal((await request('/auth/guest',{},'POST','','https://attacker.test')).status,403);
    assert.equal((await request('/session',null,'GET')).data.guestAllowed,true);
    const guest=await request('/auth/guest');assert.equal(guest.status,200);assert.equal(guest.data.user.isGuest,true);assert.equal(guest.data.user.email,null);
    const cookie=guest.response.headers.get('Set-Cookie').split(';')[0];
    assert.match(guest.response.headers.get('Set-Cookie'),/HttpOnly; Secure; SameSite=Lax; Max-Age=21600/);
    assert.equal((await request('/auth/guest',{},'POST',cookie)).data.user.id,guest.data.user.id);
    assert.equal((await request('/connections/DeepSeek',{key:'local-guest-key'},'POST',cookie)).status,200);
    assert(!DB.sqlite.prepare('SELECT encrypted_key FROM connections').get().encrypted_key.includes('local-guest-key'));
    const id=crypto.randomUUID();
    assert.equal((await request('/ask',{provider:'DeepSeek',question:'免登录测试',requestId:id},'POST',cookie)).status,200);
    assert.equal((await request('/session',null,'GET',cookie)).data.user.id,guest.data.user.id);
    assert.equal((await request('/history',null,'GET',cookie)).data.conversations.length,1);
    const calls=mocks.calls.length;
    assert.equal((await request('/history/'+id,null,'GET',cookie)).data.answers[0].state,'done');
    assert.equal(mocks.calls.length,calls);
    const other=await request('/auth/guest'),otherCookie=other.response.headers.get('Set-Cookie').split(';')[0];
    assert.equal((await request('/connections',null,'GET',otherCookie)).data.connections.length,0);
    assert.equal((await request('/history/'+id,null,'GET',otherCookie)).status,404);
    env.ALLOW_GUEST_TEST='false';
    assert.equal((await request('/connections',null,'GET',cookie)).status,401);
    env.ALLOW_GUEST_TEST='true';
    assert.equal((await request('/auth/logout',{},'POST',cookie)).status,200);
    for(const table of ['connections','conversations','requests','sessions'])assert.equal(DB.sqlite.prepare(`SELECT COUNT(*) n FROM ${table} WHERE user_id=?`).get(guest.data.user.id).n,0);
    assert.equal((await request('/history',null,'GET',cookie)).status,401);
    DB.sqlite.prepare('INSERT INTO users(id,email,created_at) VALUES(?,?,?)').run('registered','registered@example.test',Date.now());
    await request('/connections/DeepSeek',{key:'local-guest-key'},'POST',otherCookie);
    DB.sqlite.prepare('UPDATE users SET guest_expires_at=1 WHERE id=?').run(other.data.user.id);
    assert.equal((await request('/connections',null,'GET',otherCookie)).status,401);
    assert.equal((await request('/session',null,'GET',otherCookie)).data.user,null);
    assert.equal(DB.sqlite.prepare('SELECT COUNT(*) n FROM users WHERE guest_expires_at IS NOT NULL').get().n,0);
    assert.equal(DB.sqlite.prepare('SELECT COUNT(*) n FROM connections').get().n,0);
    assert(DB.sqlite.prepare("SELECT id FROM users WHERE id='registered'").get());
    assert.equal(mocks.deliveries.length,0);
  } finally {mocks.restore();DB.sqlite.close();}
});

test('email authentication, credential isolation and five-provider requests', async()=>{
  const DB=createDatabase(); const mocks=mockServices();
  const env={DB,PRISM_SECRET:'local-test-secret-only',RESEND_API_KEY:'local-mail-mock',AUTH_FROM_EMAIL:'PRISM <test@example.test>'};
  const origin='https://prism.test';
  let cookie='';
  async function request(path,data,method='POST',customCookie=cookie,customOrigin=origin) {
    const response=await worker.fetch(new Request(origin+'/api'+path,{method,headers:{Origin:customOrigin,Cookie:customCookie,'Content-Type':'application/json'},body:method==='GET'?undefined:JSON.stringify(data||{})}),env,{});
    return {response,status:response.status,data:await response.json()};
  }
  try {
    assert.equal((await request('/connections',null,'GET')).status,401);
    assert.equal((await request('/auth/request',{email:'user@example.test',intent:'login'})).data.code,'NOT_REGISTERED');
    assert.equal((await request('/auth/request',{email:'user@example.test',intent:'register'},'POST','','https://attacker.test')).status,403);
    let sent=await request('/auth/request',{email:'user@example.test',intent:'register'});
    assert.equal(sent.status,200);
    const code=mocks.deliveries.at(-1).text.match(/\d{6}/)[0];
    assert.equal((await request('/auth/verify',{challengeId:sent.data.challengeId,code:'xxxxxx'})).status,400);
    const login=await request('/auth/verify',{challengeId:sent.data.challengeId,code});
    assert.equal(login.status,200); assert.equal(login.data.user.email,'user@example.test');
    cookie=login.response.headers.get('Set-Cookie').split(';')[0];
    assert.match(login.response.headers.get('Set-Cookie'),/HttpOnly; Secure; SameSite=Lax/);
    assert.equal((await request('/auth/verify',{challengeId:sent.data.challengeId,code})).status,400);
    assert.equal((await request('/session',null,'GET')).data.user.email,'user@example.test');
    assert.equal((await request('/auth/request',{email:'user@example.test',intent:'register'})).data.code,'ALREADY_REGISTERED');
    const names=['ChatGPT','Claude','Gemini','DeepSeek','Grok'];
    for(const name of names) assert.equal((await request('/connections/'+name,{key:'local-test-key-'+name})).status,200);
    const rows=DB.sqlite.prepare('SELECT encrypted_key FROM connections').all();
    assert(rows.every(row=>!row.encrypted_key.includes('local-test-key')));
    const listing=await request('/connections',null,'GET');
    assert.equal(listing.data.connections.length,5);assert(!JSON.stringify(listing.data).includes('encrypted_key'));
    assert.equal((await request('/connections/ChatGPT',{model:'invented-model'})).status,400);
    assert.equal((await request('/connections/ChatGPT',{key:'invalid-test-key'})).status,400);
    assert.equal((await request('/connections',null,'GET')).data.connections.length,5);
    const requestId=crypto.randomUUID();
    const answers=await Promise.all(names.map(provider=>request('/ask',{provider,question:'测试问题',requestId})));
    assert(answers.every(answer=>answer.status===200 && answer.data.text.includes('本地接口测试')));
    assert.equal(mocks.calls.length,5);
    await request('/ask',{provider:'ChatGPT',question:'测试问题',requestId});
    assert.equal(mocks.calls.length,5,'retries must not bill a duplicate request');
    const saved=await request('/history',null,'GET');
    assert.equal(saved.data.conversations.length,1);
    assert.equal(saved.data.conversations[0].question,'测试问题');
    assert.equal(saved.data.conversations[0].answer_count,5);
    const restored=await request('/history/'+requestId,null,'GET');
    assert.equal(restored.data.answers.length,5);
    assert(restored.data.answers.every(answer=>answer.state==='done'));
    assert.equal(mocks.calls.length,5,'history reads must never generate new answers');
    assert.equal((await request('/ask',{provider:'DeepSeek',question:'改写原问题',requestId:crypto.randomUUID(),conversationId:requestId})).status,409);
    mocks.failures.set('api.deepseek.com',429);
    const partialId=crypto.randomUUID();
    const partial=await Promise.all(['DeepSeek','ChatGPT'].map(provider=>request('/ask',{provider,question:'单个平台失败测试',requestId:partialId})));
    assert.equal(partial[0].status,502);assert.equal(partial[1].status,200);
    const failedHistory=await request('/history/'+partialId,null,'GET');
    assert.equal(failedHistory.data.answers.find(a=>a.provider==='DeepSeek').state,'error');
    assert.match(failedHistory.data.answers.find(a=>a.provider==='DeepSeek').error,/额度|频率/);
    mocks.failures.clear();
    const beforeRetry=mocks.calls.length;
    const retried=await request('/ask',{provider:'DeepSeek',question:'单个平台失败测试',conversationId:partialId,requestId:crypto.randomUUID()});
    assert.equal(retried.status,200);assert.equal(mocks.calls.length,beforeRetry+1);
    assert.equal(mocks.calls.at(-1).host,'api.deepseek.com');
    const retryHistory=await request('/history/'+partialId,null,'GET');
    assert.equal(retryHistory.data.answers.length,2,'latest retry replaces its earlier failed attempt');
    assert(retryHistory.data.answers.every(a=>a.state==='done'));
    assert.equal((await request('/ask',{provider:'DeepSeek',question:'单个平台失败测试',conversationId:partialId,requestId:crypto.randomUUID()})).status,409);
    assert.equal(mocks.calls.length,beforeRetry+1,'successful answers must not be retried accidentally');
    assert.equal((await request('/ask',{provider:'ChatGPT',question:'不同的问题',requestId})).status,409);
    const simultaneousId=crypto.randomUUID(), beforeConcurrent=mocks.calls.length;
    const simultaneous=await Promise.all([1,2].map(()=>request('/ask',{provider:'DeepSeek',question:'并发重试测试',conversationId:simultaneousId,requestId:crypto.randomUUID()})));
    assert.deepEqual(simultaneous.map(r=>r.status).sort(),[200,409]);
    assert.equal(mocks.calls.length,beforeConcurrent+1,'parallel retries must call the provider only once');
    sent=await request('/auth/request',{email:'other@example.test',intent:'register'});
    const other=await request('/auth/verify',{challengeId:sent.data.challengeId,code:mocks.deliveries.at(-1).text.match(/\d{6}/)[0]});
    const otherCookie=other.response.headers.get('Set-Cookie').split(';')[0];
    assert.equal((await request('/connections',null,'GET',otherCookie)).data.connections.length,0);
    assert.equal((await request('/history',null,'GET',otherCookie)).data.conversations.length,0);
    assert.equal((await request('/history/'+requestId,null,'GET',otherCookie)).status,404);
    assert.equal((await request('/ask',{provider:'ChatGPT',question:'测试',requestId:crypto.randomUUID()},'POST',otherCookie)).status,409);
    const expired=await request('/auth/request',{email:'expired@example.test',intent:'register'});
    DB.sqlite.prepare('UPDATE challenges SET expires_at=0 WHERE id=?').run(expired.data.challengeId);
    assert.equal((await request('/auth/verify',{challengeId:expired.data.challengeId,code:mocks.deliveries.at(-1).text.match(/\d{6}/)[0]})).status,400);
    await request('/connections/Grok',{},'DELETE');
    assert.equal((await request('/connections',null,'GET')).data.connections.length,4);
    await request('/auth/logout',{});
    assert.equal((await request('/connections',null,'GET')).status,401);
    delete env.RESEND_API_KEY;
    assert.equal((await request('/auth/request',{email:'new@example.test',intent:'register'})).data.code,'MAIL_NOT_CONFIGURED');
    console.log('Verified OTP, encrypted keys, five adapters, persistent history, isolated single-provider retries, concurrent deduplication, cross-user isolation and logout. External services were mocked.');
  } finally {mocks.restore();DB.sqlite.close();}
});
